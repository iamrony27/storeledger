/**
 * Pure TypeScript SHA-256 Cryptographic Checksum Implementation
 * 
 * Works identically across Node.js (tests), Web, Expo Go, and standalone Android APK
 * without requiring native modules or binary dependencies.
 * Compliant with FIPS 180-4 standard.
 */

function rightRotate(n: number, count: number): number {
  return (n >>> count) | (n << (32 - count));
}

